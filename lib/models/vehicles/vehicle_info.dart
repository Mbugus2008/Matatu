class Vehicle {
  final int id;
  final String vehicleNumber;
  final String fleetNumber;
  final String make;
  final String model;
  final int year;

  Vehicle({
    required this.id,
    required this.vehicleNumber,
    required this.fleetNumber,
    required this.make,
    required this.model,
    required this.year,
  });
}
